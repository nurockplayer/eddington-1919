#!/usr/bin/env python3
"""Generate scripts/palette.gd from art/palette.toml (the single palette source).

    python3 art/pipeline/palette_to_gd.py

Godot cannot read art/ in an exported build (art/.gdignore), so the game gets a
generated constant table instead. Re-run after any palette change; the
benchmark (G4) will show the effect.
"""
import colorsys
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sw = tomllib.loads((ROOT / "art/palette.toml").read_text())["swatch"]

# Enforce BIBLE §4 before generating: value 0.08–0.82 (evidence may exceed), saturation ≤ 0.65.
bad = []
for k, v in sw.items():
    h = v["hex"].lstrip("#")
    _, s_, v_ = colorsys.rgb_to_hsv(*(int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)))
    if s_ > 0.65 or v_ < 0.08 or (v_ > 0.82 and v["role"] != "evidence"):
        bad.append(f"{k} {v['hex']} S={s_:.2f} V={v_:.2f}")
if bad:
    sys.exit("palette violates BIBLE §4:\n  " + "\n  ".join(bad))
lines = [
    "extends RefCounted",
    "## GENERATED by art/pipeline/palette_to_gd.py from art/palette.toml. Do not edit.",
    "## Albedo colours (sRGB) by swatch name; see art/BIBLE.md §4 for roles and value rules.",
    "",
    "const C := {",
]
for k, v in sw.items():
    h = v["hex"].lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))
    lines.append(f'\t"{k}": Color({r:.3f}, {g:.3f}, {b:.3f}),  # {v["role"]}')
lines += ["}", "", "const ROUGH := {"]
for k, v in sw.items():
    lines.append(f'\t"{k}": {v.get("roughness", 0.8)},')
lines += ["}", ""]
(ROOT / "scripts/palette.gd").write_text("\n".join(lines))
print("wrote scripts/palette.gd with", len(sw), "swatches")
